"""release-audit-report's Step 0 verdict, Step 1 gather plan and check, and Step 3 PR proposal.

Pure functions over what `release-config preflight` / `load --skill
audit-report` printed and the facts the agent read. Nothing here searches a
mail archive, reads the planning issue, runs `svn` or opens a PR: the agent
does the reading, the release manager confirms the PR (Golden rules 1 and 2).
The Step 2 record itself is `record.py`.
"""

from __future__ import annotations

import re
from typing import Any

from release_management.audit_report import record
from release_management.shell import dq, w
from release_management.vote_tally import tally

# `apache/airflow#45200`, `https://github.com/apache/airflow/issues/45200`, with an optional
# trailing slash or `#issuecomment-…` anchor; `#45200` alone when the upstream is known.
SHORT_REF = re.compile(r"^(?P<org>[A-Za-z0-9][A-Za-z0-9._-]*)/(?P<repo>[A-Za-z0-9._-]+)#(?P<n>[1-9][0-9]*)$")
ISSUE_URL = re.compile(
    r"^https://github\.com/(?P<org>[A-Za-z0-9][A-Za-z0-9._-]*)/(?P<repo>[A-Za-z0-9._-]+)"
    r"/issues/(?P<n>[1-9][0-9]*)/?(?:#[A-Za-z0-9_-]*)?$"
)
BARE_REF = re.compile(r"^#(?P<n>[1-9][0-9]*)$")
# The one permalink shape a PonyMail thread has.
PONYMAIL_THREAD = re.compile(r"^https://lists\.apache\.org/thread/[A-Za-z0-9._-]+(?:\?[^\s<>()\[\]`|]*)?$")
LINK_FIELDS = ("vote_thread_url", "result_thread_url", "announce_archive_url")
DEFAULT_BODY_FILE = "<scratch>/audit-report-pr-body.md"
PR_TITLE = "chore: add release audit record for {product} {version}"
GENERATED_BY = "Generated by `release-audit-report` (magpie-release-audit-report)."
MISSING_NOTE = (
    "The source data for these fields was not recorded on the planning issue.\n"
    "A maintainer may update the audit record manually once the data is available."
)
REDACTED_NOTE = (
    "These fields exist in non-public sources and were excluded from the public\n"
    "audit log per the privacy boundary in `docs/release-management/spec.md`."
)


class RenderError(ValueError):
    """The inputs ask for something the skill must not propose."""


# --------------------------------------------------------------------------- Step 0


def planning_issue_url(ref: str, upstream: str | None = None) -> str | None:
    """`ref` as the canonical `https://github.com/<org>/<repo>/issues/<n>`, or None when it is not one."""
    text = ref.strip()
    for pattern in (SHORT_REF, ISSUE_URL):
        match = pattern.match(text)
        if match:
            return f"https://github.com/{match['org']}/{match['repo']}/issues/{match['n']}"
    bare = BARE_REF.match(text)
    if bare and upstream and re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]*/[A-Za-z0-9._-]+", upstream):
        return f"https://github.com/{upstream}/issues/{bare['n']}"
    return None


def verdict(
    preflight: dict[str, Any],
    *,
    planning_issue: str | None,
    upstream: str | None = None,
    searched: str | None = None,
) -> dict[str, Any]:
    """Step 0: the tool's blockers plus the planning-issue check, with the URL normalised."""
    values = preflight.get("values") or {}
    version = values.get("version")
    blockers = [str(b) for b in preflight.get("blockers") or []]
    url: str | None = None
    if planning_issue:
        url = planning_issue_url(planning_issue, upstream)
        if url is None:
            blockers.append(
                f"planning issue reference {planning_issue!r} is not a GitHub issue: "
                "pass --planning-issue https://github.com/<org>/<repo>/issues/<n>"
            )
    else:
        term = searched or str(version or "<version>")
        where = f" on {upstream}" if upstream else ""
        blockers.append(
            f'no planning issue found{where} matching "{term}" in its title; '
            "pass --planning-issue <url> to name it explicitly"
        )
    return {
        "verdict": "blocked" if blockers else "proceed",
        "blockers": blockers,
        "planning_issue_url": url,
        "audit_log_path": values.get("audit_log_path") or None,
        "warnings": [str(x) for x in preflight.get("warnings") or []],
    }


# --------------------------------------------------------------------------- Step 1


def _render(text: str, version: str, product: str, rc: str | None) -> str:
    out = text
    for spelling in ("<version>-<rcN>", "<version>-rcN", "<version>-rc<N>"):
        out = out.replace(spelling, f"{version}-{rc}" if rc else f"{version}-<rcN>")
    return (
        out.replace("<version>", version)
        .replace("<Product Name>", product)
        .replace("<product_name>", product)
    )


def _query(subject: str) -> str:
    """The subject up to its first unrendered placeholder: the search term that still matches."""
    cut = subject.split("<", 1)[0]
    return cut.rstrip(" -").strip() or subject


def _lists(value: Any) -> list[str]:
    if not value:
        return []
    items = value if isinstance(value, list) else str(value).split(",")
    return [str(item).strip() for item in items if str(item).strip()]


def _archive_url(template: Any, mailing_list: str, version: str, product: str) -> str | None:
    if not template:
        return None
    url = _render(str(template), version, product, None)
    for key in ("<dev-list>", "<vote-list>", "<vote_dev_list>", "<list>", "<announce-list>"):
        url = url.replace(key, mailing_list)
    return None if re.search(r"<[^>]+>", url) else url


def gather(
    loaded: dict[str, Any],
    *,
    version: str | None = None,
    rc: str | None = None,
    schema_text: str | None = None,
) -> dict[str, Any]:
    """Step 1: what to search for each lifecycle URL, the promote-revision recipe and the field list.

    The searches themselves stay with the agent: this only says which list, which
    subject and which permalink shape counts.
    """
    config = loaded.get("config") or {}
    meta = loaded.get("metadata") or {}
    version = version or meta.get("version")
    if not version:
        raise RenderError("no version: run release-config load with --skill audit-report <version>")
    version = str(version)
    project = str(config.get("project_dist_name") or "<project>")
    product = str(config.get("product_name") or project)
    is_ponymail = str(config.get("mail_archive") or "").lower() == "ponymail"
    vote_list = str(config.get("vote_dev_list") or "<dev-list>")
    announce_list = config.get("announce_list")
    announce_lists = [*_lists(announce_list), *_lists(config.get("announce_cc_lists"))] or ["<announce-list>"]
    template = config.get("mail_archive_url_template")
    subjects = {
        "vote_thread_url": (
            config.get("vote_subject_template")
            or "[VOTE] Release <Product Name> <version> from <version>-rcN",
            [vote_list],
        ),
        "result_thread_url": (
            config.get("result_subject_template")
            or "[RESULT] [VOTE] Release <Product Name> <version> from <version>-rcN",
            [vote_list],
        ),
        "announce_archive_url": (
            config.get("announce_subject_template") or "[ANNOUNCE] <Product Name> <version> released",
            announce_lists,
        ),
    }
    searches = []
    for field, (subject_template, lists) in subjects.items():
        subject = _render(str(subject_template), version, product, rc)
        searches.append(
            {
                "field": field,
                "subject": subject,
                "query": _query(subject),
                "lists": lists,
                "archive_urls": [
                    u for u in (_archive_url(template, m, version, product) for m in lists) if u
                ],
            }
        )
    backend = str(config.get("release_dist_backend") or "")
    target = meta.get("target_url")
    promote: dict[str, Any] = {"backend": backend, "command": None, "note": None}
    if backend == "svnpubsub" and target:
        promote["command"] = f"svn info --show-item last-changed-revision {w(target)}"
        promote["note"] = (
            "the revision of the Step 10 `svn mv` commit that created the promoted directory; "
            "record it as r<N>"
        )
    else:
        promote["note"] = (
            f"no lookup recipe for release_dist_backend {backend or '<unset>'!r}: take the backend-equivalent "
            "identifier from the planning issue, else MISSING"
        )
    return {
        "version": version,
        "product_name": product,
        "mail_archive": config.get("mail_archive"),
        "permalink_shape": "https://lists.apache.org/thread/<id>" if is_ponymail else None,
        "searches": searches,
        "promote_revision": promote,
        "roster_path": (loaded.get("derived") or {}).get("approver_roster_path")
        or config.get("release_approver_roster_path"),
        "required_fields": record.required_fields(schema_text) if schema_text else None,
    }


def _handles(roster_text: str) -> dict[str, str]:
    """Lower-cased Apache ID → the handle to cite: the GitHub column when the table has one, else the ID as written."""
    out: dict[str, str] = {}
    header: list[str] | None = None
    for line in roster_text.splitlines():
        if "|" not in line:
            continue
        cells = [c.strip().strip("`").strip() for c in line.strip().strip("|").split("|")]
        lowered = [c.lower() for c in cells]
        if "apache id" in lowered:
            header = lowered
            continue
        if header is None:
            continue
        row = dict(zip(header, cells, strict=False))
        apache_id = row.get("apache id", "")
        handle = next((row[k] for k in ("github", "github handle", "handle") if row.get(k)), "") or apache_id
        if apache_id:
            out[apache_id.lower()] = handle.lstrip("@")
    return out


def voters(entries: list[Any], roster_text: str) -> dict[str, Any]:
    """`[RESULT]` binding voters → roster handles, with vote-tally's binding resolution (Golden rule 5).

    Each entry is a `From:` address, an `<id>@apache.org` address or a bare Apache ID.
    A voter the roster does not resolve is never cited: it comes back in
    `unresolved` for the RM, and no address ever reaches `binding_voters`.
    """
    roster = tally.parse_roster(roster_text)
    if not roster:
        raise RenderError("roster has no rows with an Apache ID / Primary email header")
    cited = _handles(roster_text)
    ids = {row["apache_id"] for row in roster if row["apache_id"]}
    handles: list[str] = []
    unresolved: list[str] = []
    for entry in entries:
        sender = str(entry.get("from") if isinstance(entry, dict) else entry).strip()
        apache_id: str | None = None
        if "@" not in sender and sender.lstrip("@").lower() in ids:
            apache_id = sender.lstrip("@").lower()
        elif tally.resolve_binding(sender, roster) is not None:
            address = tally.normalise_address(sender)
            apache_id = next(
                (
                    row["apache_id"]
                    for row in roster
                    if row["apache_id"]
                    and address in (row["primary_email"], f"{row['apache_id']}@apache.org")
                ),
                None,
            )
        if apache_id is None:
            unresolved.append(sender)
            continue
        handle = "@" + cited.get(apache_id, apache_id)
        if handle not in handles:
            handles.append(handle)
    return {"binding_voters": handles or record.MISSING, "unresolved": unresolved}


def check(data: dict[str, Any], required: list[str], *, ponymail: bool = True) -> dict[str, Any]:
    """Step 1 check: the sentinel lists, schema violations and every value Step 2 would refuse.

    `record.render` computes the same lists at Step 2; running them here lets the
    agent surface a refused link or voter before the RM confirms the gathered fields.
    """
    fields_missing = [
        f for f in record.ORDERED_FIELDS if record.sentinel(data.get(f, record.MISSING)) == "MISSING"
    ]
    fields_redacted = [f for f in record.ORDERED_FIELDS if record.sentinel(data.get(f)) == "REDACTED"]
    problems: list[str] = []
    for field in LINK_FIELDS:
        value = data.get(field, record.MISSING)
        if record.sentinel(value):
            continue
        url = str(value).strip()
        if not record.SAFE_URL_RE.fullmatch(url):
            problems.append(f"{field} must be a plain https:// URL, MISSING or REDACTED")
        elif ponymail and url.startswith("https://lists.apache.org/") and not PONYMAIL_THREAD.match(url):
            problems.append(
                f"{field} is not a thread permalink (https://lists.apache.org/thread/<id>): {url}"
            )
    planning = data.get("planning_issue_url")
    if not planning:
        problems.append("planning_issue_url is absent")
    elif planning_issue_url(str(planning)) != str(planning).strip():
        problems.append(f"planning_issue_url is not the canonical issue URL: {planning}")
    voters_value = data.get("binding_voters", record.MISSING)
    if not record.sentinel(voters_value):
        try:
            record.render_value("binding_voters", voters_value, {})
        except record.InputError as exc:
            problems.append(str(exc))
    reasons = data.get("redaction_reasons") or {}
    gaps = [
        f"{f} is REDACTED but has no entry in redaction_reasons"
        for f in fields_redacted
        if not reasons.get(f)
    ]
    if data.get("injection_flagged") and not data.get("injection_sources"):
        gaps.append("injection_flagged is true but injection_sources is empty")
    schema = set(required)
    return {
        "fields_missing": fields_missing,
        "fields_redacted": fields_redacted,
        "schema_violations": [f"{f} — required field is MISSING" for f in fields_missing if f in schema],
        "problems": problems,
        "input_gaps": gaps,
    }


# --------------------------------------------------------------------------- Step 3


def pr(
    data: dict[str, Any],
    *,
    audit_log_path: str,
    upstream: str | None = None,
    base: str | None = None,
    body_file: str = DEFAULT_BODY_FILE,
) -> dict[str, Any]:
    """Step 3: the audit-log PR title, body and target file, proposed and never opened."""
    if not audit_log_path:
        raise RenderError("audit_log_path is unset: Step 0 should have blocked")
    version = data.get("version")
    if not version or not re.fullmatch(r"[0-9][A-Za-z0-9.+-]*", str(version)):
        raise RenderError(f"version {version!r} is not a release version")
    given = str(data.get("planning_issue_url") or "").strip()
    planning = planning_issue_url(given)
    if planning is None or planning != given:
        raise RenderError("planning_issue_url is not a canonical GitHub issue URL")
    product = " ".join(str(data.get("product_name") or "<project>").split())
    reasons = data.get("redaction_reasons") or {}
    fields_missing = [
        f for f in record.ORDERED_FIELDS if record.sentinel(data.get(f, record.MISSING)) == "MISSING"
    ]
    fields_redacted = [f for f in record.ORDERED_FIELDS if record.sentinel(data.get(f)) == "REDACTED"]
    title = PR_TITLE.format(product=product, version=version)
    lines = [
        f"Adds the release audit record for {record.text(product)} {version}.",
        "",
        f"Source: planning issue {planning}",
        "",
    ]
    if fields_missing:
        lines += [f"**Fields missing at report time**: {', '.join(fields_missing)}", MISSING_NOTE, ""]
    if fields_redacted:
        listed = ", ".join(
            f"{f} ({record.text(reasons[f])})" if reasons.get(f) else f for f in fields_redacted
        )
        lines += [f"**Fields redacted**: {listed}", REDACTED_NOTE, ""]
    lines.append(GENERATED_BY)
    target = f"{audit_log_path.rstrip('/')}/{version}.md"
    repo = upstream or "<upstream>"
    body = body_file if body_file == DEFAULT_BODY_FILE else w(body_file)
    branch = base or "<default-branch>"
    command = f"gh pr create --web --repo {w(repo)} --title {dq(title)} --body-file {body} --base {w(branch)}"
    return {
        "audit_log_path": audit_log_path,
        "target_file": target,
        "pr_title": title,
        "pr_body": "\n".join(lines) + "\n",
        "proposed": True,
        "gh_command": command,
    }
