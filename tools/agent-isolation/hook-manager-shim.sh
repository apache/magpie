# hook-manager-shim.sh — a transparent front for a git-hook manager
# (prek and overcommit today; see tools/hook-manager/registry.json), installed as
# `~/.claude/bin/<tool>` with `~/.claude/bin` prepended to PATH so it
# shadows the real binary. The tool is the name it is installed
# under (`basename "$0"`), so one script serves every adapter.
#
# WHY THIS EXISTS
# ---------------
# Under **whole-user (global) scope**, the framework sets
#   git config --global core.hooksPath ~/.claude/git-hooks/
# which makes git resolve hooks from ONE shared directory for every
# repo. A hook manager then either refuses to install (prek since
# 0.5: "core.hooksPath is configured outside this repository") or
# writes its hook into that shared dir instead of the repo's own
# `.git/hooks/` — collapsing every repo onto a single shared hook and
# colliding with the framework's dispatchers.
#
# With the framework's per-repo **dispatcher** hooks installed in
# the shared dir (git-hook-dispatcher.sh), the correct arrangement
# is the opposite: the manager's hook belongs in each repo's *local*
# `.git/hooks/`, where the dispatcher chains into it. This is the
# contract's *install target* rule (tools/hook-manager/README.md).
#
# WHAT THIS SHIM DOES
# -------------------
#   * `<tool> <install action> [...]` -> rewritten per the
#     adapter's install strategy so the hook lands in
#     "$(git rev-parse --git-common-dir)/hooks" (absolute, worktree-
#     safe: `--git-common-dir` resolves linked worktrees to the main
#     checkout's hooks dir) — UNLESS the caller already chose a
#     target, asked for help, or we are not inside a git work tree.
#     A flag-style action and its registry aliases are found anywhere
#     in argv (`overcommit --force --install`, `overcommit -i`); a
#     positional action is only argv[0] (`prek install`).
#       git-dir-flag: inject `<flag> <common dir>` (prek: --git-dir)
#       hooks-path-env: append GIT_CONFIG_* so the manager writes to
#       `<common dir>/hooks` (overcommit: --install, -i)
#   * every other invocation (`prek run`, `prek autoupdate`,
#     `--version`, bare `prek`, ...) is passed through to the real
#     binary **unchanged**.
#
# The shim is a no-op on hosts that never set a global
# core.hooksPath — installing into `.git/hooks/` is exactly where a
# bare install would have put it anyway, so the rewrite is harmless
# when there is no global hooks dir.

set -euo pipefail

tool="$(basename "$0")"

# --- adapters: generated from tools/hook-manager/registry.json -------------
# BEGIN generated by tools/dev/sync-hook-managers.py; do not edit
adapter() {
  case "$1" in
    overcommit) install_subcommand=--install; install_strategy=hooks-path-env; install_aliases='--install -i' ;;
    prek) install_subcommand=install; install_strategy=git-dir-flag; install_flag=--git-dir ;;
    *) return 1 ;;
  esac
}
# END generated by tools/dev/sync-hook-managers.py

if ! adapter "$tool"; then
  echo "hook-manager-shim: no adapter for '$tool' in tools/hook-manager/registry.json" >&2
  echo "hook-manager-shim: (install this script under an adapter's name, e.g. ~/.claude/bin/prek)" >&2
  exit 127
fi

# --- locate the REAL binary: the next `$tool` on PATH that is not us -------
self_canon="$(readlink -f "$0" 2>/dev/null || echo "$0")"
real_tool=""
IFS=':' read -ra _path_dirs <<<"${PATH:-}"
for _d in "${_path_dirs[@]}"; do
  [ -n "$_d" ] || continue
  _cand="$_d/$tool"
  [ -x "$_cand" ] || continue
  _cand_canon="$(readlink -f "$_cand" 2>/dev/null || echo "$_cand")"
  [ "$_cand_canon" = "$self_canon" ] && continue   # skip ourselves
  real_tool="$_cand"
  break
done

if [ -z "$real_tool" ]; then
  echo "hook-manager-shim: could not locate the real '$tool' binary on PATH" >&2
  echo "hook-manager-shim: (this wrapper must sit ahead of $tool, not replace it)" >&2
  exit 127
fi

# --- only rewrite the install action; everything else is transparent -------
# A positional subcommand (`prek install`) is only the first argument. A
# flag-style action (`overcommit --install`) may follow other options, so scan
# the whole argv for it and its aliases (`overcommit -i`). Option parsers such
# as Ruby's OptionParser also take a single-letter alias inside a bundle of
# short switches (`-fi`) and an unambiguous prefix of a long one (`--inst`),
# so those count too; rewriting a non-install run only points core.hooksPath
# at the repository's own hooks, which is harmless.
install_invoked=0
case "$install_subcommand" in
  -*)
    install_actions="${install_aliases:-$install_subcommand}"
    for _a in "$@"; do
      for _action in $install_actions; do
        case "$_action" in
          --*)
            # Any prefix (`--i` on): fail closed, since a wrongly rewritten run is harmless.
            if [ "${#_a}" -ge 3 ] && [ "${_action#"$_a"}" != "$_action" ]; then
              install_invoked=1
              break 2
            fi
            ;;
          -?)
            case "$_a" in
              --*) ;;
              -*"${_action#-}"*)
                install_invoked=1
                break 2
                ;;
            esac
            ;;
          *)
            if [ "$_a" = "$_action" ]; then
              install_invoked=1
              break 2
            fi
            ;;
        esac
      done
    done
    ;;
  *)
    [ "${1:-}" = "$install_subcommand" ] && install_invoked=1
    ;;
esac

if [ "$install_invoked" = 0 ]; then
  exec "$real_tool" "$@"
fi

# Respect a target the caller chose, and never interfere with help output.
inject=1
for _a in "$@"; do
  case "$_a" in
    -h|--help) inject=0; break ;;
  esac
  if [ -n "${install_flag:-}" ]; then
    case "$_a" in
      "$install_flag"|"$install_flag"=*) inject=0; break ;;
    esac
  fi
done

if [ "$inject" = 1 ]; then
  if gitdir="$(git rev-parse --git-common-dir 2>/dev/null)"; then
    case "$gitdir" in
      /*) : ;;                                   # already absolute
      *)  gitdir="$(cd "$gitdir" 2>/dev/null && pwd -P || echo "$gitdir")" ;;
    esac
    case "$install_strategy" in
      git-dir-flag)
        # Only positional actions use this strategy; the action is argv[0].
        shift
        exec "$real_tool" "$install_subcommand" "$install_flag" "$gitdir" "$@"
        ;;
      hooks-path-env)
        # Append at the next index so a caller's GIT_CONFIG_* entries survive.
        _i="${GIT_CONFIG_COUNT:-0}"
        case "$_i" in
          ''|*[!0-9]*) _i=0 ;;
        esac
        export "GIT_CONFIG_KEY_$_i=core.hooksPath"
        export "GIT_CONFIG_VALUE_$_i=${gitdir%/}/hooks"
        export GIT_CONFIG_COUNT=$((_i + 1))
        exec "$real_tool" "$@"
        ;;
    esac
  fi
  # not in a git work tree: let the real tool produce its own error
fi

exec "$real_tool" "$@"
