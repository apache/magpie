# hook-manager-shim.sh — a transparent front for a git-hook manager
# (prek, overcommit, lefthook and CaptainHook today; see
# tools/hook-manager/registry.json), installed as `~/.claude/bin/<tool>`
# with `~/.claude/bin` prepended to PATH so it shadows the real binary.
# The tool is the name it is installed under (`basename "$0"`), so one
# script serves every adapter.
#
# WHY THIS EXISTS
# ---------------
# Under **whole-user (global) scope**, the framework sets
#   git config --global core.hooksPath ~/.claude/git-hooks/
# which makes git resolve hooks from ONE shared directory for every
# repo. A hook manager then either refuses to install (prek since
# 0.5: "core.hooksPath is configured outside this repository") or
# writes its hook into that shared dir instead of the repo's own
# `.git/hooks/` — collapsing every repo onto a single shared hook and
# colliding with the framework's dispatchers.
#
# With the framework's per-repo **dispatcher** hooks installed in
# the shared dir (git-hook-dispatcher.sh), the correct arrangement
# is the opposite: the manager's hook belongs in each repo's *local*
# `.git/hooks/`, where the dispatcher chains into it. This is the
# contract's *install target* rule (tools/hook-manager/README.md).
#
# WHAT THIS SHIM DOES
# -------------------
#   * `<tool> <install action> [...]` -> rewritten per the
#     adapter's install strategy so the hook lands in
#     "$(git rev-parse --git-common-dir)/hooks" (absolute, worktree-
#     safe: `--git-common-dir` resolves linked worktrees to the main
#     checkout's hooks dir) — UNLESS the caller already chose a
#     target, asked for help, or we are not inside a git work tree.
#     A flag-style action and its registry aliases are found anywhere
#     in argv (`overcommit --force --install`, `overcommit -i`); a
#     positional action is argv[0] (`prek install`) unless the adapter
#     sets `install.match: prefix`, for a manager whose option parser
#     takes global options before the command and resolves a prefix of
#     it (`captainhook -n install`, `captainhook inst`) — then any
#     non-option argument that prefixes the action counts.
#       git-dir-flag: inject `<flag> <common dir>` (prek: --git-dir)
#       hooks-path-env: append GIT_CONFIG_* so the manager writes to
#       `<common dir>/hooks` (overcommit: --install, -i; captainhook:
#       install)
#       hide-global-config: run the install with
#         GIT_CONFIG_GLOBAL=/dev/null, for a manager that writes to
#         the common dir itself but refuses while a global
#         core.hooksPath is set (lefthook). The override applies only
#         when the global config actually holds a core.hooksPath, so an
#         ordinary host keeps its credential and url.* settings, and
#         even then it applies with `--force` / `--reset-hooks-path`:
#         through this shim those must not write into the shared dir or
#         unset the whole-user setup. Run the real binary to bypass it.
#   * every other invocation (`prek run`, `prek autoupdate`,
#     `--version`, bare `prek`, ...) is passed through to the real
#     binary **unchanged**.
#   * when PATH holds no real binary, an adapter with
#     `install.vendor_bin` runs the copy a Composer project keeps in
#     `<repository root>/vendor/bin/<tool>`, which is not on PATH.
#   * a CaptainHook install warns when a CaptainHook Composer plugin is
#     enabled, because that plugin installs on every `composer install`
#     and `composer update` without passing through this shim.
#
# The shim is a no-op on hosts that never set a global
# core.hooksPath — installing into `.git/hooks/` is exactly where a
# bare install would have put it anyway, so the rewrite is harmless
# when there is no global hooks dir.

set -euo pipefail

tool="$(basename "$0")"

# --- adapters: generated from tools/hook-manager/registry.json -------------
# BEGIN generated by tools/dev/sync-hook-managers.py; do not edit
adapter() {
  case "$1" in
    captainhook) install_subcommand=install; install_strategy=hooks-path-env; install_match=prefix; install_vendor_bin=1 ;;
    lefthook) install_subcommand=install; install_strategy=hide-global-config ;;
    overcommit) install_subcommand=--install; install_strategy=hooks-path-env; install_aliases='--install -i' ;;
    prek) install_subcommand=install; install_strategy=git-dir-flag; install_flag=--git-dir ;;
    *) return 1 ;;
  esac
}
# END generated by tools/dev/sync-hook-managers.py

if ! adapter "$tool"; then
  echo "hook-manager-shim: no adapter for '$tool' in tools/hook-manager/registry.json" >&2
  echo "hook-manager-shim: (install this script under an adapter's name, e.g. ~/.claude/bin/prek)" >&2
  exit 127
fi

# --- locate the REAL binary: the next `$tool` on PATH that is not us -------
# `readlink -f` is not on every macOS, so fall back to resolving the symlink
# chain and the directory with the POSIX tools that are everywhere.
_canonical() {
  if _cp="$(readlink -f "$1" 2>/dev/null)"; then
    printf '%s\n' "$_cp"
    return 0
  fi
  _cp="$1"
  while [ -L "$_cp" ]; do
    _ct="$(readlink "$_cp" 2>/dev/null)" || break
    case "$_ct" in
      /*) _cp="$_ct" ;;
      *)  _cp="$(dirname "$_cp")/$_ct" ;;
    esac
  done
  _cd="$(cd "$(dirname "$_cp")" 2>/dev/null && pwd -P)" || {
    printf '%s\n' "$_cp"
    return 0
  }
  printf '%s\n' "$_cd/$(basename "$_cp")"
}

self_canon="$(_canonical "$0")"
real_tool=""
IFS=':' read -ra _path_dirs <<<"${PATH:-}"
for _d in "${_path_dirs[@]}"; do
  [ -n "$_d" ] || continue
  _cand="$_d/$tool"
  [ -x "$_cand" ] || continue
  _cand_canon="$(_canonical "$_cand")"
  [ "$_cand_canon" = "$self_canon" ] && continue   # skip ourselves
  real_tool="$_cand"
  break
done

if [ -z "$real_tool" ] && [ "${install_vendor_bin:-0}" = 1 ]; then
  # A Composer project keeps the binary in vendor/bin, which is not on
  # PATH; resolve it from the repository root the command runs in. The
  # candidate can be a symlink back to this shim, so it gets the same
  # self-check as the PATH walk.
  if _root="$(git rev-parse --show-toplevel 2>/dev/null)" && [ -x "$_root/vendor/bin/$tool" ]; then
    _cand="$_root/vendor/bin/$tool"
    _cand_canon="$(_canonical "$_cand")"
    if [ "$_cand_canon" = "$self_canon" ]; then
      echo "hook-manager-shim: $_cand is this shim" >&2
      echo "hook-manager-shim: (this wrapper must sit ahead of $tool, not replace it)" >&2
      exit 127
    fi
    real_tool="$_cand"
  fi
fi

if [ -z "$real_tool" ]; then
  echo "hook-manager-shim: could not locate the real '$tool' binary on PATH" >&2
  echo "hook-manager-shim: (this wrapper must sit ahead of $tool, not replace it)" >&2
  exit 127
fi

# CaptainHook's Composer plugins install on every `composer install` and
# `composer update`, behind this shim. Warn when an install through the shim
# would be undone by the next dependency update: the plugin is enabled when
# composer.json requires it and neither its own `disable-plugin` block nor
# `config.allow-plugins` turns it off.
warn_composer_plugin() {
  [ "$tool" = captainhook ] || return 0
  _root="$(git rev-parse --show-toplevel 2>/dev/null)" || return 0
  [ -f "$_root/composer.json" ] || return 0
  _state="$(_composer_plugin_state "$_root/composer.json")" || return 0
  [ "$_state" = enabled ] || return 0
  echo "hook-manager-shim: a CaptainHook Composer plugin is enabled in $_root/composer.json" >&2
  echo "hook-manager-shim: composer install/update will install behind this shim; set extra.captainhook.disable-plugin to true" >&2
}

# `none`, `enabled` or `disabled`, read from the plugin's own keys rather
# than a text match, so a `disable-plugin` under another package's `extra`
# cannot silence the warning. Needs python3; without it the check is
# skipped rather than guessed.
_composer_plugin_state() {
  command -v python3 >/dev/null 2>&1 || return 1
  python3 - "$1" <<'PY'
import json
import sys

PACKAGES = ("captainhook/hook-installer", "captainhook/plugin-composer")

try:
    with open(sys.argv[1], encoding="utf-8") as handle:
        data = json.load(handle)
except (OSError, ValueError):
    raise SystemExit(1)

if not isinstance(data, dict):
    raise SystemExit(1)

required = [
    name
    for section in ("require", "require-dev")
    for name in (data.get(section) or {})
    if name in PACKAGES
]
if not required:
    print("none")
    raise SystemExit(0)

extra = data.get("extra")
block = extra.get("captainhook") if isinstance(extra, dict) else None
if isinstance(block, dict) and block.get("disable-plugin") is True:
    print("disabled")
    raise SystemExit(0)

config = data.get("config")
allow = config.get("allow-plugins") if isinstance(config, dict) else None
if allow is False or (isinstance(allow, dict) and all(allow.get(name) is False for name in required)):
    print("disabled")
    raise SystemExit(0)

print("enabled")
PY
}

# --- only rewrite the install action; everything else is transparent -------
# A positional subcommand (`prek install`) is only the first argument. A
# flag-style action (`overcommit --install`) may follow other options, so scan
# the whole argv for it and its aliases (`overcommit -i`). Option parsers such
# as Ruby's OptionParser also take a single-letter alias inside a bundle of
# short switches (`-fi`) and an unambiguous prefix of a long one (`--inst`),
# so those count too; rewriting a non-install run only points core.hooksPath
# at the repository's own hooks, which is harmless.
install_invoked=0
case "$install_subcommand" in
  -*)
    install_actions="${install_aliases:-$install_subcommand}"
    for _a in "$@"; do
      for _action in $install_actions; do
        case "$_action" in
          --*)
            # Any prefix (`--i` on): fail closed, since a wrongly rewritten run is harmless.
            if [ "${#_a}" -ge 3 ] && [ "${_action#"$_a"}" != "$_action" ]; then
              install_invoked=1
              break 2
            fi
            ;;
          -?)
            case "$_a" in
              --*) ;;
              -*"${_action#-}"*)
                install_invoked=1
                break 2
                ;;
            esac
            ;;
          *)
            if [ "$_a" = "$_action" ]; then
              install_invoked=1
              break 2
            fi
            ;;
        esac
      done
    done
    ;;
  *)
    if [ "${install_match:-exact}" = prefix ]; then
      # A Symfony Console app takes global options before the command and
      # resolves an unambiguous prefix of it (`captainhook -n install`,
      # `captainhook inst`). Any non-option argument that prefixes the
      # action counts, so a global option's value cannot hide the command
      # behind it; treating a run as an install only points core.hooksPath
      # at the repository's own hooks, which is harmless.
      for _a in "$@"; do
        case "$_a" in
          -*) continue ;;
        esac
        if [ "${install_subcommand#"$_a"}" != "$install_subcommand" ]; then
          install_invoked=1
          break
        fi
      done
    else
      [ "${1:-}" = "$install_subcommand" ] && install_invoked=1
    fi
    ;;
esac

if [ "$install_invoked" = 0 ]; then
  exec "$real_tool" "$@"
fi

# --- install strategies: one hand-written branch per install_strategy ------
# (tools/dev/sync-hook-managers.py lists them in STRATEGIES and generates only
# the adapter() block above.)
case "$install_strategy" in
  git-dir-flag)
    # Only positional actions use this strategy; the action is argv[0].
    shift  # drop the install subcommand
    # Respect a target the caller chose, and never interfere with help output.
    inject=1
    for _a in "$@"; do
      case "$_a" in
        -h|--help) inject=0; break ;;
        "$install_flag"|"$install_flag"=*) inject=0; break ;;
      esac
    done

    if [ "$inject" = 1 ]; then
      if gitdir="$(git rev-parse --git-common-dir 2>/dev/null)"; then
        case "$gitdir" in
          /*) : ;;                                   # already absolute
          *)  gitdir="$(cd "$gitdir" 2>/dev/null && pwd -P || echo "$gitdir")" ;;
        esac
        exec "$real_tool" "$install_subcommand" "$install_flag" "$gitdir" "$@"
      fi
      # not in a git work tree: let the real tool produce its own error
    fi
    exec "$real_tool" "$install_subcommand" "$@"
    ;;
  hooks-path-env)
    # Never interfere with help output.
    inject=1
    for _a in "$@"; do
      case "$_a" in
        -h|--help) inject=0; break ;;
      esac
    done

    if [ "$inject" = 1 ]; then
      if gitdir="$(git rev-parse --git-common-dir 2>/dev/null)"; then
        case "$gitdir" in
          /*) : ;;                                   # already absolute
          *)  gitdir="$(cd "$gitdir" 2>/dev/null && pwd -P || echo "$gitdir")" ;;
        esac
        # Append at the next index so a caller's GIT_CONFIG_* entries survive.
        _i="${GIT_CONFIG_COUNT:-0}"
        case "$_i" in
          ''|*[!0-9]*) _i=0 ;;
        esac
        export "GIT_CONFIG_KEY_$_i=core.hooksPath"
        export "GIT_CONFIG_VALUE_$_i=${gitdir%/}/hooks"
        export GIT_CONFIG_COUNT=$((_i + 1))
        warn_composer_plugin "$@"
        exec "$real_tool" "$@"
      fi
      # not in a git work tree: let the real tool produce its own error
    fi
    ;;
  hide-global-config)
    shift  # drop the install subcommand
    # Never interfere with help output.
    for _a in "$@"; do
      case "$_a" in
        -h|--help) exec "$real_tool" "$install_subcommand" "$@" ;;
      esac
    done

    if git rev-parse --git-common-dir >/dev/null 2>&1; then
      # Hide the global config only when it holds a core.hooksPath to hide: the
      # override also costs the install the operator's credential.helper,
      # url.*.insteadOf and safe.directory, and the manager can clone remote
      # configs while installing.
      if [ -n "$(git config --global --get core.hooksPath 2>/dev/null)" ]; then
        GIT_CONFIG_GLOBAL=/dev/null exec "$real_tool" "$install_subcommand" "$@"
      fi
    fi
    # not in a git work tree: let the real tool produce its own error
    exec "$real_tool" "$install_subcommand" "$@"
    ;;
esac

exec "$real_tool" "$@"
