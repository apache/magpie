"""release-prepare Steps 2a, 2c, 2d and 2f, and Step 14b.

The current version in each manifest, the attribution paragraphs a NOTICE
diff removes or adds, the changelog grouping and its coverage, and the prep
and post-release PR drafts with their scope check. Whether a removed
attribution is still needed, and whether a new dependency needs a LICENSE
entry, stay with the agent: those read the dependency tree.
"""

from __future__ import annotations

import configparser
import difflib
import json
import re
import tomllib
import xml.etree.ElementTree as ET
from datetime import UTC, datetime
from pathlib import Path, PurePosixPath
from typing import Any

from release_management.prepare import plan

FOOTER = "Generated by `release-prepare` (magpie-release-prepare)."
COVERAGE_MIN = 90
SECTIONS = ("Features", "Bug fixes", "Documentation", "Other changes")
ARCHIVE_REVIEW = ("proposed", "confirmed-existing", "skipped")
ARCHIVE_MODES = ("full", "drift", "skipped")
DEFAULT_RELEASE_BUILD = "<project-config>/release-build.md"
NOTICE_HANDOFF = (
    "NOTICE attribution removed for a dependency still present in the tree. Justify the removal or revert it."
)
NEVER_IN_POST = re.compile(r"^(NOTICE|LICENSE)(\.[A-Za-z]+)?$", re.IGNORECASE)

#: The default label → changelog section map, by the words of a label name
#: (`kind/bug-fix` → `bug`, `fix`). `changelog_label_categories` or
#: `--category LABEL=SECTION` replaces it for an exact label.
KEYWORDS = {
    "Features": {"feature", "features", "enhancement", "enhancements"},
    "Bug fixes": {"bug", "bugs", "bugfix", "fix", "fixes"},
    "Documentation": {"doc", "docs", "documentation"},
    "Other changes": {
        "chore",
        "improvement",
        "improvements",
        "refactor",
        "refactoring",
        "maintenance",
        "dependencies",
        "deps",
        "misc",
        "test",
        "tests",
        "ci",
        "build",
        "perf",
        "performance",
        "cleanup",
    },
}


class RenderError(ValueError):
    """The draft cannot be rendered from these inputs; the skill surfaces this and stops."""


# --------------------------------------------------------------------------- 2a — current versions


def _first_group(pattern: str, text: str) -> str | None:
    m = re.search(pattern, text, re.MULTILINE)
    if not m:
        return None
    return (m.group(1) if m.groups() else m.group(0)).strip()


def extract_version(path: Path, name: str | None = None) -> tuple[str | None, str | None]:
    """(version, detail) for one manifest file, as `release-verify version` reads it; version is None when not found."""
    if not path.is_file():
        return None, "file not found"
    text = path.read_text(errors="replace")
    name = name or path.name
    if name == "setup.cfg":
        cfg = configparser.ConfigParser(interpolation=None)
        cfg.read_string(text)
        value = cfg.get("metadata", "version", fallback=None)
        if value and value.strip().startswith(("attr:", "file:")):
            return None, f"dynamic version ({value.strip()})"
        return (value.strip(), None) if value else (None, "no [metadata] version")
    if name in ("pyproject.toml", "Cargo.toml"):
        data = tomllib.loads(text)
        if name == "Cargo.toml":
            value = data.get("package", {}).get("version")
        else:
            project = data.get("project", {})
            if "version" in project.get("dynamic", []):
                return None, "dynamic version ([project] dynamic)"
            value = project.get("version") or data.get("tool", {}).get("poetry", {}).get("version")
        return (value, None) if isinstance(value, str) else (None, "no version key")
    if name == "pom.xml":
        if "<!DOCTYPE" in text or "<!ENTITY" in text:
            return None, "pom.xml declares a DOCTYPE/ENTITY; not parsed"
        root = ET.fromstring(text)
        ns = root.tag[: root.tag.index("}") + 1] if root.tag.startswith("{") else ""
        node = root.find(f"{ns}version")
        if node is not None and node.text:
            return node.text.strip(), None
        return None, "no <project><version> (inherited from parent?)"
    if name == "package.json":
        value = json.loads(text).get("version")
        return (value, None) if isinstance(value, str) else (None, "no version key")
    if name.endswith(".py"):
        pattern = (
            r"""^\s*version\s*=\s*['"]([^'"]+)['"]"""
            if name == "setup.py"
            else r"""^__version__\s*(?::\s*[\w.]+\s*)?=\s*['"]([^'"]+)['"]"""
        )
        found = _first_group(pattern, text)
        return found, None if found else "no version assignment"
    if name.endswith(".properties"):
        found = _first_group(r"^\s*version\s*[=:]\s*(\S+)\s*$", text)
        return found, None if found else "no version property"
    if name in ("build.gradle", "build.gradle.kts"):
        found = _first_group(r"""^\s*version\s*=?\s*['"]([^'"]+)['"]""", text)
        return found, None if found else "no version assignment"
    if name in ("Chart.yaml", "Chart.yml"):
        found = _first_group(r"""^version:\s*['"]?([^'"\s]+)""", text)
        return found, None if found else "no version key"
    if name in ("VERSION", "version.txt", "VERSION.txt"):
        line = next((ln.strip() for ln in text.splitlines() if ln.strip()), None)
        return line, None if line else "empty file"
    return None, "no known extraction pattern for this file type: read the current string yourself"


def versions(target: str, files: list[tuple[str, str]]) -> dict[str, Any]:
    """2a: the current version string each manifest carries, to be replaced by `target`."""
    out = []
    for shown, local in files:
        try:
            found, detail = extract_version(Path(local), PurePosixPath(shown).name)
        except (ValueError, tomllib.TOMLDecodeError, ET.ParseError, configparser.Error) as exc:
            found, detail = None, f"could not parse: {exc}"
        entry: dict[str, Any] = {"file": shown, "current": found, "target": target}
        if detail:
            entry["detail"] = detail
        if found == target:
            entry["already_target"] = True
        out.append(entry)
    found_values = {e["current"] for e in out if e["current"]}
    return {
        "target_version": target,
        "files": out,
        "current_dev_version": found_values.pop() if len(found_values) == 1 else None,
        "needs_reading": [e["file"] for e in out if e["current"] is None],
    }


# --------------------------------------------------------------------------- 2c — NOTICE diff


def notice_changes(diff: str) -> dict[str, Any]:
    """2c: the attribution paragraphs a NOTICE diff removes and adds (a unified diff or a GitHub `patch`)."""
    removed: list[str] = []
    added: list[str] = []
    runs: dict[str, list[str]] = {"-": [], "+": []}

    def flush(sign: str) -> None:
        if runs[sign]:
            (removed if sign == "-" else added).append(" ".join(runs[sign]))
            runs[sign] = []

    for line in diff.splitlines():
        if line.startswith(("diff --git", "index ", "--- ", "+++ ", "@@", "\\ No newline")):
            flush("-")
            flush("+")
            continue
        sign = line[:1]
        if sign in ("-", "+"):
            text = line[1:].strip()
            if text:
                runs[sign].append(re.sub(r"\s+", " ", text))
            else:
                flush(sign)
            continue
        flush("-")
        flush("+")
    flush("-")
    flush("+")
    return {
        "removed_attributions": removed,
        "added_attributions": added,
        "handoff_reason_if_unjustified": NOTICE_HANDOFF,
    }


def notice_diff(old: str | None, new: str) -> dict[str, Any]:
    """2c: `notice_changes` over the two whole NOTICE files (`old` is None when the previous tag had none)."""
    diff = difflib.unified_diff(
        (old or "").splitlines(), new.splitlines(), "a/NOTICE", "b/NOTICE", lineterm=""
    )
    return notice_changes("\n".join(diff))


# --------------------------------------------------------------------------- 2d — changelog


def _words(label: str) -> set[str]:
    return {w.lower() for w in re.split(r"[^A-Za-z0-9]+", label) if w}


def section_for(labels: list[str], categories: dict[str, str]) -> str | None:
    for label in labels:
        if label in categories:
            return categories[label]
        words = _words(label)
        for section, keys in KEYWORDS.items():
            if words & keys:
                return section
    return None


def parse_categories(raw: Any) -> dict[str, str]:
    """`changelog_label_categories` (a list or comma-separated `LABEL=SECTION`) as a map."""
    items = raw if isinstance(raw, list) else str(raw or "").split(",")
    out: dict[str, str] = {}
    for item in items:
        label, sep, section = str(item).partition("=")
        if sep and label.strip() and section.strip():
            out[label.strip()] = section.strip()
    return out


def changelog(
    prs: list[dict[str, Any]],
    *,
    version: str,
    date: str | None = None,
    categories: dict[str, str] | None = None,
    assigned: dict[int, str] | None = None,
) -> dict[str, Any]:
    """2d: the entry grouped by section, and whether at least 90% of the PRs fall in one by label."""
    cats = categories or {}
    forced = assigned or {}
    buckets: dict[str, list[dict[str, Any]]] = {}
    uncategorised: list[dict[str, Any]] = []
    for pr in prs:
        number = int(pr.get("number") or 0)
        section = forced.get(number) or section_for(plan.label_names(pr), cats)
        if section is None:
            uncategorised.append(pr)
            section = "Other changes"
        buckets.setdefault(section, []).append(pr)
    order = [s for s in SECTIONS if s in buckets] + sorted(s for s in buckets if s not in SECTIONS)
    day = date or datetime.now(UTC).strftime("%Y-%m-%d")
    lines = [f"## {version} ({day})"]
    for section in order:
        lines += ["", f"### {section}"]
        lines += [
            f"- #{pr.get('number')} {plan.inert_title(pr.get('title'))} ([#{pr.get('number')}]({pr.get('url')}))"
            for pr in buckets[section]
        ]
    total = len(prs)
    categorised = total - len(uncategorised)
    pct = 100 if total == 0 else categorised * 100 // total
    ok = categorised * 100 >= total * COVERAGE_MIN
    return {
        "entry": "\n".join(lines),
        "pr_count": total,
        "changelog_coverage_pct": pct,
        "coverage_ok": ok,
        "uncategorised": [
            {"number": pr.get("number"), "title": pr.get("title"), "labels": plan.label_names(pr)}
            for pr in uncategorised
        ],
        "read": [] if ok else ["classifications/changelog-coverage-low.md"],
    }


# --------------------------------------------------------------------------- scope (2f, 14b)


def _norm(path: str) -> str:
    return str(PurePosixPath(path.strip().strip("`").removeprefix("./")))


def scope(
    proposed: list[str], allowed: list[str], confirmed: list[str] | None = None
) -> tuple[list[str], list[str], list[str]]:
    """(in scope, violations, confirmed extras): the proposed files minus the allowed set, unless confirmed."""
    allow = {_norm(a) for a in allowed}
    ok = {_norm(c) for c in confirmed or []}
    in_scope, violations, extras = [], [], []
    for path in proposed:
        key = _norm(path)
        if key in allow:
            in_scope.append(path)
        elif key in ok:
            in_scope.append(path)
            extras.append(path)
        else:
            violations.append(path)
    return in_scope, violations, extras


def _bullets(files: list[str]) -> list[str]:
    return [f"- {f}" for f in files]


def _scope_read(violations: list[str]) -> list[str]:
    return ["classifications/scope-violation.md"] if violations else []


# --------------------------------------------------------------------------- 2f — prep PR


def prep_pr(
    *,
    version: str,
    product_name: str,
    manifests: list[str],
    current_version: str | None,
    log: dict[str, Any],
    previous_tag: str | None,
    changelog_file: str | None = None,
    notice_summary: str | None = None,
    files: list[str],
    archive_mode: str,
    archive_review: str = "skipped",
    archive_entries: list[tuple[str, str]] | None = None,
    release_build: str = DEFAULT_RELEASE_BUILD,
    confirmed_extra: list[str] | None = None,
) -> dict[str, Any]:
    """2f: the prep PR title, body and scope; refuses low changelog coverage and an inconsistent archive review.

    `files` is every file the diff touches; `archive_mode` is the `mode` that
    2e's `archive-mode` printed.
    """
    if archive_review not in ARCHIVE_REVIEW:
        raise RenderError(f"archive_review {archive_review!r} is not one of {', '.join(ARCHIVE_REVIEW)}")
    if archive_mode not in ARCHIVE_MODES:
        raise RenderError(f"archive mode {archive_mode!r} is not one of {', '.join(ARCHIVE_MODES)}")
    if archive_mode == "full" and archive_review == "skipped":
        raise RenderError(
            "archive-mode said `full`: the source-archive review is due, so archive_review cannot be `skipped`"
        )
    if archive_mode == "skipped" and archive_review != "skipped":
        raise RenderError(
            f"archive-mode said `skipped` (custom source archive): archive_review cannot be `{archive_review}`"
        )
    entries = archive_entries or []
    if archive_review == "proposed" and not entries:
        raise RenderError("archive_review is `proposed` but no --archive-entry was given")
    if archive_review != "proposed" and entries:
        raise RenderError(f"--archive-entry given but archive_review is `{archive_review}`")
    if not log.get("coverage_ok"):
        raise RenderError(
            f"changelog coverage is {log.get('changelog_coverage_pct')}% (< {COVERAGE_MIN}%): "
            "the RM classifies the uncategorised PRs (`--assign N=SECTION`) before the prep PR opens"
        )
    if not current_version:
        raise RenderError(
            "no current development version: read it from the manifests and pass --current-version"
        )
    expected = list(manifests)
    if changelog_file:
        expected.append(changelog_file)
    expected += ["NOTICE", "LICENSE"]
    archive_files = {
        "proposed": [".gitattributes", release_build],
        "confirmed-existing": [release_build],
    }.get(archive_review, [])
    expected += archive_files
    if not files:
        raise RenderError("--files is every file the diff touches: pass at least one")
    in_scope, violations, extras = scope(files, expected, confirmed_extra)

    count = log.get("pr_count", 0)
    since = f" since {previous_tag}" if previous_tag else ""
    body = [
        f"Release prep for {product_name} {version}.",
        "",
        "## Changes",
        "",
        "### Version bump",
        "Files updated:",
        *_bullets(manifests),
        f"`{current_version}` → `{version}`",
        "",
        "### Changelog",
        f"Entry added for {version} covering {count} merged PRs{since}.",
        "",
        "### NOTICE/LICENSE",
        notice_summary or "No changes required.",
    ]
    if archive_review == "proposed":
        body += ["", "### Source archive contents"]
        body += [f"- `{line}` — {reason}" for line, reason in entries]
        body.append(f"- release-build.md: export_ignore_reviewed set to {version}")
    elif archive_review == "confirmed-existing":
        body += [
            "",
            "### Source archive contents",
            "- The existing `.gitattributes` export-ignore entries were reviewed and confirmed unchanged.",
            f"- release-build.md: export_ignore_reviewed set to {version}",
        ]
    body += [
        "",
        "## Checklist (RM)",
        "- [ ] Version bump is correct in all manifest files",
        "- [ ] Changelog entry covers the intended scope",
        "- [ ] NOTICE attribution changes are justified",
        "- [ ] No Category-X dependency appears in the diff",
        "- [ ] (first release) every `export-ignore` entry was reviewed; LICENSE / NOTICE / build inputs still ship",
        "",
        FOOTER,
    ]
    return {
        "pr_title": f"chore: prepare {version} release",
        "pr_body": "\n".join(body),
        "files_in_scope": in_scope,
        "scope_violations": violations,
        "category_x_hit": False,
        "notice_removal_unjustified": False,
        "changelog_coverage_pct": log.get("changelog_coverage_pct"),
        "archive_review": archive_review,
        "proposed": True,
        "confirmed_out_of_scope": extras,
        "read": _scope_read(violations),
    }


# --------------------------------------------------------------------------- 14b — post-release PR


def post_pr(
    nxt: dict[str, Any],
    *,
    product_name: str,
    files: list[str],
    next_version: str | None = None,
    changelog_file: str | None = None,
    confirmed_extra: list[str] | None = None,
) -> dict[str, Any]:
    """14b: the bump PR from what `next-dev-version` printed; NOTICE, LICENSE and the changelog never join it.

    `files` is every file the diff touches; `changelog_file` is the configured one.
    """
    changelog = _norm(changelog_file) if changelog_file else None
    for path in confirmed_extra or []:
        if NEVER_IN_POST.match(PurePosixPath(_norm(path)).name) or _norm(path) == changelog:
            raise RenderError(f"{path} is never part of the post-release bump (Golden rule 5)")
    if not files:
        raise RenderError("--files is every file the diff touches: pass at least one")
    entries = nxt.get("files") or []
    manifests = [str(e["file"]) for e in entries if e.get("configured")]
    if next_version is None:
        values = {e.get("next_dev_version") for e in entries if e.get("configured")}
        pending = [
            str(e["file"]) for e in entries if e.get("configured") and e.get("next_dev_version") is None
        ]
        if pending:
            raise RenderError(
                f"no next development version for {', '.join(pending)}: "
                "surface the current string and pass the RM's confirmed value as --next-version"
            )
        if len(values) != 1:
            raise RenderError(
                f"the files propose different next versions ({', '.join(sorted(str(v) for v in values))}): "
                "pass the RM's confirmed value as --next-version"
            )
        next_version = str(values.pop())
    version = str(nxt.get("current_version"))
    in_scope, violations, extras = scope(files, manifests, confirmed_extra)
    body = "\n".join(
        [
            f"Post-release version bump after {product_name} {version}.",
            "",
            "## Changes",
            "",
            "### Version bump",
            "Files updated:",
            *_bullets(manifests),
            f"`{version}` → `{next_version}`",
            "",
            FOOTER,
        ]
    )
    return {
        "pr_title": f"chore: bump version to {next_version} after {version} release",
        "pr_body": body,
        "current_version": version,
        "next_dev_version": next_version,
        "files_in_scope": in_scope,
        "scope_violations": violations,
        "proposed": True,
        "confirmed_out_of_scope": extras,
        "read": _scope_read(violations),
    }
