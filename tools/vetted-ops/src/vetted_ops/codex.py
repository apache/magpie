"""Render native Codex rules for the installed, fixed vetted-ops path.

Print only: installing this policy is an explicit operator action. Paths are
absolute and never `~`: execpolicy rejects a word containing `~`, and a `~` rule
would be unsafe, since the shell resolves it from a reassignable `HOME` and `uv`
treats it as a relative directory. Only the read entry point is allowlisted;
both write entry points always prompt.

`--hook` prints the Codex-only PreToolUse hook that rewrites the `~` spelling
skills use to this absolute path before the rules see it
(`hooks/codex-expand-stable-path.py`).
"""

from __future__ import annotations

import argparse
import json
import shlex
from pathlib import Path


def render_rules(tool_root: Path) -> str:
    if not tool_root.is_absolute():
        raise ValueError("tool root must be an absolute installed path")
    # Keep the stable symlink spelling. Resolving it would pin a plugin version.
    base = str(tool_root)
    lines = [
        "# SPDX-License-Identifier: Apache-2.0",
        "# Generated by vetted-ops-codex-rules; review before installing.",
    ]
    for launcher in (("uv", "run", "--project"), ("uvx", "--from")):
        for entry in ("vetted-op-read", "vetted-op", "vetted-op-tracker"):
            pattern = [*launcher, base, entry]
            decision = "allow" if entry == "vetted-op-read" else "prompt"
            lines.append(f"prefix_rule(pattern = {json.dumps(pattern)}, decision = {json.dumps(decision)})")
    return "\n".join(lines) + "\n"


def render_hook(tool_root: Path) -> str:
    if not tool_root.is_absolute():
        raise ValueError("tool root must be an absolute installed path")
    script = tool_root / "hooks" / "codex-expand-stable-path.py"
    command = f"python3 {shlex.quote(str(script))} --stable-path {shlex.quote(str(tool_root))}"
    return (
        "\n".join(
            [
                "# SPDX-License-Identifier: Apache-2.0",
                "# Generated by vetted-ops-codex-rules --hook; review before installing.",
                "# Codex configuration only: Claude Code reads this hook's output as a permission grant.",
                "[[hooks.PreToolUse]]",
                'matcher = "^Bash$"',
                "",
                "[[hooks.PreToolUse.hooks]]",
                'type = "command"',
                f"command = {json.dumps(command)}",
                "timeout = 10",
                'statusMessage = "Spelling the vetted-ops path absolute"',
            ]
        )
        + "\n"
    )


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--tool-root",
        type=Path,
        default=Path.home() / ".claude/magpie/vetted-ops",
        help="absolute installed stable path (default: shared Magpie path)",
    )
    parser.add_argument(
        "--hook",
        action="store_true",
        help="print the Codex PreToolUse hook that spells the stable path absolute",
    )
    args = parser.parse_args(argv)
    try:
        print((render_hook if args.hook else render_rules)(args.tool_root), end="")
    except ValueError as exc:
        parser.error(str(exc))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
